/**
 * Grounds rebuilt in their real blocks (core/realBlocks*.ts): the new layout
 * has the ground's name, and the layout it replaced — kept for the designs
 * saved on it — is that name marked as the earlier layout.
 */
export const EARLIER_LAYOUT_IDS: readonly string[] = Object.keys(REAL_BLOCK_IDS);
for (const [oldId, newId] of Object.entries(REAL_BLOCK_IDS)) {
  if (LABEL_KEYS[oldId] && !LABEL_KEYS[newId]) LABEL_KEYS[newId] = LABEL_KEYS[oldId];
}

