/**
 * Regenerate the subset icon font.
 *
 * @tabler/icons-webfont ships 5,754 icons: an 849 KB woff2 and a 223 KB
 * stylesheet of class rules. On a phone that was over half the editor's entire
 * download, for the ~80 icons this app actually draws. This scans src/ and the
 * HTML entries for ti-* classes, subsets the font to exactly those glyphs, and
 * writes src/vendor/tabler-subset.{woff2,css}.
 *
 * Run it after adding a new icon, or that icon renders as an empty box:
 *   node scripts/build-icon-subset.mjs
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const walk = (dir, out = []) => {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) { if (e !== 'vendor' && e !== 'node_modules') walk(p, out); }
    else if (['.ts', '.html', '.css'].includes(extname(p))) out.push(p);
  }
  return out;
};
const files = [...walk(join(ROOT, 'src')), ...readdirSync(ROOT).filter((f) => f.endsWith('.html')).map((f) => join(ROOT, f))];
const used = new Set();
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/\bti-[a-z0-9-]+/g)) used.add(m[0]);

const fontCss = readFileSync(join(ROOT, 'node_modules/@tabler/icons-webfont/dist/tabler-icons.min.css'), 'utf8');
const pairs = [...fontCss.matchAll(/\.(ti-[a-z0-9-]+):before\{content:"\\([0-9a-fA-F]+)"\}/g)]
  .map((m) => [m[1], m[2]])
  .filter(([n]) => used.has(n));
if (!pairs.length) throw new Error('no icons matched — did the upstream CSS format change?');

mkdirSync(join(ROOT, 'src/vendor'), { recursive: true });
const srcFont = join(ROOT, 'node_modules/@tabler/icons-webfont/dist/fonts/tabler-icons.woff2');
const outFont = join(ROOT, 'src/vendor/tabler-subset.woff2');
execFileSync('python3', ['-m', 'fontTools.subset', srcFont,
  `--unicodes=${pairs.map(([, c]) => 'U+' + c.toUpperCase()).join(',')}`,
  '--flavor=woff2', `--output-file=${outFont}`,
  '--layout-features=', '--no-hinting', '--desubroutinize'], { stdio: 'inherit' });

const css = `/**
 * Tabler icons, subset to the ${pairs.length} glyphs this app actually uses.
 * GENERATED by scripts/build-icon-subset.mjs — do not edit by hand.
 */
@font-face {
  font-family: 'tabler-icons';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url('./tabler-subset.woff2') format('woff2');
}
.ti {
  font-family: 'tabler-icons' !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${pairs.map(([n, c]) => `.${n}:before { content: "\\${c}"; }`).join('\n')}
`;
writeFileSync(join(ROOT, 'src/vendor/tabler-subset.css'), css);
console.log(`subset ${pairs.length} icons  ·  ${Math.round(statSync(srcFont).size / 1024)} KB -> ${Math.round(statSync(outFont).size / 1024)} KB font, ${Math.round(css.length / 1024)} KB css`);
