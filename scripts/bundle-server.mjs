/**
 * Bundles the server into one file, server/build/server.mjs, which is what the
 * container runs (performance plan P1.31).
 *
 * The server used to start under tsx, which transpiled ~220 KB of TypeScript
 * on every boot (1.4-1.8 s of a cold start, plus an esbuild service process
 * and ~40 MB). Bundling does that once, in the Docker build.
 *
 * What the bundle must never be, each checked by test:deploy:
 *  - in dist/: that is the public web root, served to anyone. server/build/
 *    sits beside server/src, so the paths the server finds its data by
 *    (../schema.sql, ../data/*, ../../dist) are the same from both;
 *  - carrying a secret: no `define`, so process.env is read when the server
 *    runs, never baked in at build time;
 *  - carrying a source map: none is written, inline or beside it;
 *  - hiding a dependency: every package stays an import (`packages:
 *    'external'`), resolved from node_modules at run time, so npm audit,
 *    Dependabot and the posture panel still see exactly what runs.
 */
import { realpathSync } from 'node:fs';
import { resolve as resolvePath } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export const BUNDLE_OPTIONS = {
  entryPoints: ['server/src/server.ts'],
  outfile: 'server/build/server.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  packages: 'external',
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by scripts/bundle-server.mjs from server/src. Not served; do not edit.' },
};

// Run as a script (not imported by test:deploy). Compared as resolved paths: a
// plain string compare of URLs failed silently for a path with a space or
// through a symlink, exiting 0 with no bundle written.
if (process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(resolvePath(process.argv[1]))) {
  const outfile = process.argv[2] ?? BUNDLE_OPTIONS.outfile;
  const started = Date.now();
  await build({ ...BUNDLE_OPTIONS, outfile });
  console.log(`server bundle: ${outfile} (${Date.now() - started} ms)`);
}
