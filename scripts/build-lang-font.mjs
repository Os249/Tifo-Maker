/**
 * Regenerate the tiny font the language toggle uses on English pages
 * (performance plan P2.8).
 *
 * An English page shows one Arabic word, the "العربية" button, and drew it in
 * Almarai, which meant a 33 KB Arabic font file on every English page view for
 * seven letters. This subsets the same Almarai files, in the weights the site
 * uses (400/700/800), to exactly the letters of that label with their joining
 * forms and every layout feature, so the word looks exactly as before, and
 * writes:
 *
 *   src/vendor/almarai-toggle-<weight>.woff2   about 5 KB each
 *   src/vendor/almarai-toggle.css              their @font-face rules
 *
 * ui/fonts.css gives this family to the language toggles only: anywhere else
 * a word mixing its letters with others would be drawn from two fonts and
 * lose its joins. The label is read from src/ui/i18n/strings.ts
 * ('common.language', English side), and the build checks that the font still
 * covers it (scripts/vite/fontPreload.ts). Same origin, like every other font
 * (font-src 'self').
 *
 * Run it after changing that label:
 *   node scripts/build-lang-font.mjs
 * Needs python3 with fonttools and brotli (pip install fonttools brotli).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const strings = readFileSync(join(ROOT, 'src/ui/i18n/strings.ts'), 'utf8');
const m = /'common\.language':\s*\{\s*en:\s*'([^']+)'/.exec(strings);
if (!m) throw new Error("could not find the English side of 'common.language' in src/ui/i18n/strings.ts");
const label = m[1];
const points = [...new Set([...label].map((c) => c.codePointAt(0)))].sort((a, b) => a - b);
if (!points.every((p) => p >= 0x0600 && p <= 0x06ff)) throw new Error(`the toggle label "${label}" is not all Arabic letters`);
const range = points.map((p) => 'U+' + p.toString(16).toUpperCase().padStart(4, '0')).join(', ');

mkdirSync(join(ROOT, 'src/vendor'), { recursive: true });
const rules = [];
for (const w of [400, 700, 800]) {
  const src = join(ROOT, `node_modules/@fontsource/almarai/files/almarai-arabic-${w}-normal.woff2`);
  const out = join(ROOT, `src/vendor/almarai-toggle-${w}.woff2`);
  execFileSync('python3', ['-m', 'fontTools.subset', src, `--text=${label}`,
    // Every layout feature, so the letters join and position exactly as in the
    // full font.
    '--layout-features=*', '--flavor=woff2', `--output-file=${out}`], { stdio: 'inherit' });
  rules.push(`@font-face {
  font-family: 'Almarai Toggle';
  font-style: normal;
  font-display: swap;
  font-weight: ${w};
  src: url('./almarai-toggle-${w}.woff2') format('woff2');
  unicode-range: ${range};
}`);
  console.log(`almarai-toggle-${w}.woff2: ${statSync(out).size} bytes`);
}

writeFileSync(join(ROOT, 'src/vendor/almarai-toggle.css'), `/**
 * Almarai, subset to the letters of the language toggle's label "${label}"
 * (${range}), in the weights the site uses (performance plan P2.8).
 * GENERATED by scripts/build-lang-font.mjs — do not edit by hand.
 */
${rules.join('\n')}
`);
console.log(`label "${label}" -> ${range}`);
